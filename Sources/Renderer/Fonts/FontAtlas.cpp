std::vector<std::uint8_t> rgba()
{
    std::vector<std::uint8_t> pixels(static_cast<std::size_t>(WIDTH * HEIGHT * 4), 0u);

    for (std::size_t codepoint = 0; codepoint < glyphs.size(); ++codepoint) {
        const std::uint64_t glyph = glyphs[codepoint];
        const std::size_t glyph_x = (codepoint & 15u) * 8u;
        const std::size_t glyph_y = (codepoint >> 4u) * 8u;

        for (std::size_t y = 0; y < 8u; ++y) {
            for (std::size_t x = 0; x < 8u; ++x) {
                const std::size_t bit = y * 8u + x;
                if ((glyph & (1ull << bit)) == 0u) continue;

                const std::size_t pixel = (glyph_y + y) * static_cast<std::size_t>(WIDTH) + glyph_x + x;
                const std::size_t offset = pixel * 4u;
                pixels[offset + 0u] = 255u;
                pixels[offset + 1u] = 255u;
                pixels[offset + 2u] = 255u;
                pixels[offset + 3u] = 255u;
            }
        }
    }

    return pixels;
}

